const flights=[
 {id:"SB101",name:"SkyBook Express",from:"Chennai",to:"Delhi",depart:"06:15",arrive:"09:05",fare:4890,seats:24},
 {id:"SB205",name:"BlueSky Airways",from:"Chennai",to:"Mumbai",depart:"09:30",arrive:"11:35",fare:3590,seats:18},
 {id:"SB318",name:"CloudNine Air",from:"Delhi",to:"Bengaluru",depart:"13:20",arrive:"16:10",fare:5290,seats:31},
 {id:"SB422",name:"Southern Wings",from:"Bengaluru",to:"Chennai",depart:"18:00",arrive:"19:00",fare:2790,seats:12}
];
let bookings=[];let chosenDate="";
const $=id=>document.getElementById(id);
$("date").min=new Date().toISOString().split("T")[0];
const norm=s=>s.trim().toLowerCase();
function msg(id,text,error=false){const e=$(id);e.hidden=false;e.textContent=text;e.classList.toggle("error",error);}
function renderFlights(list){
 const box=$("flightResults");
 if(!list.length){box.className="results empty";box.textContent="No demo flights found. Try Chennai to Delhi, Chennai to Mumbai, Delhi to Bengaluru, or Bengaluru to Chennai.";return;}
 box.className="results flight-list";
 box.innerHTML=list.map(f=>`<div class="flight-card"><div><h3>${f.name} <span style="font-size:11px;color:#8190a4">(${f.id})</span></h3><p>${f.from} → ${f.to}<br>${f.depart} departure · ${f.arrive} arrival</p></div><div class="flight-price">₹${f.fare.toLocaleString("en-IN")}<small>${f.seats} demo seats available</small><button class="button primary small" data-id="${f.id}">Select Flight</button></div></div>`).join("");
 box.querySelectorAll("[data-id]").forEach(b=>b.addEventListener("click",()=>{
  const f=flights.find(x=>x.id===b.dataset.id);
  $("selectedFlight").innerHTML=`<option value="${f.id}">${f.name} (${f.id}) — ${f.from} to ${f.to}</option>`;
  $("book").scrollIntoView({behavior:"smooth"});
 }));
}
$("searchForm").addEventListener("submit",e=>{
 e.preventDefault();chosenDate=$("date").value;
 const from=norm($("from").value),to=norm($("to").value);
 renderFlights(flights.filter(f=>(norm(f.from).includes(from)||from.includes(norm(f.from)))&&(norm(f.to).includes(to)||to.includes(norm(f.to)))));
});
function newRef(){return "SB"+Math.floor(100000+Math.random()*900000);}
$("bookingForm").addEventListener("submit",e=>{
 e.preventDefault();const f=flights.find(x=>x.id===$("selectedFlight").value);
 if(!f){msg("bookingMessage","Please search and select a flight first.",true);return;}
 const b={ref:newRef(),name:$("name").value.trim(),email:$("email").value,mobile:$("mobile").value,
 passengers:$("passengers").value,payment:$("payment").value,flight:f.name,flightId:f.id,from:f.from,to:f.to,
 date:chosenDate||$("date").value,fare:f.fare,status:"Confirmed"};
 bookings.push(b);msg("bookingMessage",`Booking confirmed for ${b.name}! Your booking reference is ${b.ref}. Estimated fare per passenger: ₹${b.fare.toLocaleString("en-IN")}. Save this reference to view or cancel your ticket.`);
 $("bookingForm").reset();$("selectedFlight").innerHTML='<option value="">Search and select a flight first</option>';renderAdmin();
});
$("ticketForm").addEventListener("submit",e=>{
 e.preventDefault();const b=bookings.find(x=>x.ref.toLowerCase()===$("refInput").value.trim().toLowerCase()),box=$("ticketResult");
 if(!b){box.className="results empty";box.textContent="Booking reference not found. Enter a reference generated by this demo.";return;}
 box.className="results empty";box.innerHTML=`<strong>Reference:</strong> ${b.ref}<br><strong>Passenger:</strong> ${b.name}<br><strong>Email:</strong> ${b.email}<br><strong>Flight:</strong> ${b.flight} (${b.flightId})<br><strong>Route:</strong> ${b.from} → ${b.to}<br><strong>Date:</strong> ${b.date||"Not specified"}<br><strong>Passengers:</strong> ${b.passengers}<br><strong>Status:</strong> <span class="status ${b.status==="Cancelled"?"cancelled":""}">${b.status}</span>`;
});
$("cancelForm").addEventListener("submit",e=>{
 e.preventDefault();const b=bookings.find(x=>x.ref.toLowerCase()===$("cancelRef").value.trim().toLowerCase());
 if(!b){msg("cancelMessage","Booking reference not found in this demo.",true);return;}
 if(b.status==="Cancelled"){msg("cancelMessage","This booking is already cancelled.",true);return;}
 b.status="Cancelled";msg("cancelMessage",`Ticket ${b.ref} for ${b.name} has been cancelled in the demo system.`);renderAdmin();
});
function renderAdmin(){
 $("flightCount").textContent=flights.length;$("bookingCount").textContent=bookings.length;$("activeCount").textContent=bookings.filter(b=>b.status==="Confirmed").length;
 $("adminRows").innerHTML=bookings.length?bookings.map(b=>`<tr><td>${b.ref}</td><td>${b.name}</td><td>${b.flight}</td><td>${b.from} → ${b.to}</td><td><span class="status ${b.status==="Cancelled"?"cancelled":""}">${b.status}</span></td></tr>`).join(""):'<tr><td colspan="5">No bookings yet.</td></tr>';
}
renderAdmin();
