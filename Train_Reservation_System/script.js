const trains = [
  {id:"12601",name:"Chennai Mail",from:"Chennai",to:"Bengaluru",depart:"06:10",arrive:"11:45",fare:420,seats:48},
  {id:"12609",name:"Karnataka Express",from:"Chennai",to:"Bengaluru",depart:"08:30",arrive:"14:05",fare:560,seats:26},
  {id:"12007",name:"Shatabdi Express",from:"Chennai",to:"Bengaluru",depart:"17:00",arrive:"22:00",fare:890,seats:12},
  {id:"12640",name:"Brindavan Express",from:"Bengaluru",to:"Chennai",depart:"15:15",arrive:"20:50",fare:490,seats:32}
];
let bookings = [];
let selectedJourneyDate = "";
const $ = id => document.getElementById(id);
$("journeyDate").min = new Date().toISOString().split("T")[0];

function showMessage(id, message, error=false){
  const el=$(id); el.hidden=false; el.textContent=message; el.classList.toggle("error",error);
}
function normalized(s){return s.trim().toLowerCase();}
function renderTrains(list){
  const results=$("trainResults");
  if(!list.length){results.className="results empty-state";results.textContent="No demo trains found for this route. Try Chennai to Bengaluru or Bengaluru to Chennai.";return;}
  results.className="results train-list";
  results.innerHTML=list.map(t=>`<div class="train-card">
    <div><h3>${t.name} <span style="color:#7c8ca3;font-size:12px">(${t.id})</span></h3>
    <p>${t.from} → ${t.to}<br>${t.depart} departure · ${t.arrive} arrival</p></div>
    <div class="train-meta"><div class="fare">₹${t.fare}</div><div class="seats">${t.seats} demo seats available</div>
    <button class="primary-btn small-btn" data-train="${t.id}">Select Train</button></div></div>`).join("");
  results.querySelectorAll("[data-train]").forEach(btn=>btn.addEventListener("click",()=>{
    const t=trains.find(x=>x.id===btn.dataset.train);
    $("selectedTrain").innerHTML=`<option value="${t.id}">${t.name} (${t.id}) — ${t.from} to ${t.to}</option>`;
    $("booking").scrollIntoView({behavior:"smooth"});
  }));
}
$("searchForm").addEventListener("submit",e=>{
  e.preventDefault();
  const from=normalized($("from").value),to=normalized($("to").value);
  selectedJourneyDate=$("journeyDate").value;
  const list=trains.filter(t=>normalized(t.from).includes(from)||from.includes(normalized(t.from)))
    .filter(t=>normalized(t.to).includes(to)||to.includes(normalized(t.to)));
  renderTrains(list);
});
function newPNR(){return String(Math.floor(1000000000+Math.random()*9000000000));}
$("bookingForm").addEventListener("submit",e=>{
  e.preventDefault();
  const train=trains.find(t=>t.id===$("selectedTrain").value);
  if(!train){showMessage("bookingMessage","Please search and select a train first.",true);return;}
  const booking={pnr:newPNR(),name:$("passengerName").value.trim(),age:$("passengerAge").value,
    gender:$("gender").value,mobile:$("mobile").value,trainId:train.id,trainName:train.name,
    from:train.from,to:train.to,date:selectedJourneyDate||$("journeyDate").value,
    status:"Confirmed",fare:train.fare,payment:$("paymentMode").value};
  bookings.push(booking);
  showMessage("bookingMessage",`Booking confirmed for ${booking.name}! Your demo PNR is ${booking.pnr}. Fare: ₹${booking.fare}. Save this PNR to check status or cancel the ticket.`);
  $("bookingForm").reset(); $("selectedTrain").innerHTML='<option value="">Search and select a train first</option>';
  renderAdmin();
});
$("pnrForm").addEventListener("submit",e=>{
  e.preventDefault();
  const pnr=$("pnrInput").value.trim(),b=bookings.find(x=>x.pnr===pnr);
  const result=$("pnrResult");
  if(!b){result.className="results empty-state";result.textContent="PNR not found. Enter a PNR generated by this demo website.";return;}
  result.className="results empty-state";
  result.innerHTML=`<strong>PNR:</strong> ${b.pnr}<br><strong>Passenger:</strong> ${b.name}<br><strong>Train:</strong> ${b.trainName} (${b.trainId})<br><strong>Journey:</strong> ${b.from} → ${b.to}<br><strong>Date:</strong> ${b.date||"Not specified"}<br><strong>Status:</strong> <span class="status ${b.status==="Cancelled"?"cancelled":""}">${b.status}</span>`;
});
$("cancelForm").addEventListener("submit",e=>{
  e.preventDefault();
  const pnr=$("cancelPnr").value.trim(),b=bookings.find(x=>x.pnr===pnr);
  if(!b){showMessage("cancelMessage","PNR not found in this demo.",true);return;}
  if(b.status==="Cancelled"){showMessage("cancelMessage","This ticket is already cancelled.",true);return;}
  b.status="Cancelled";
  showMessage("cancelMessage",`Ticket ${b.pnr} for ${b.name} has been cancelled in the demo system.`);
  renderAdmin();
});
function renderAdmin(){
  $("trainCount").textContent=trains.length;
  $("bookingCount").textContent=bookings.length;
  $("activeCount").textContent=bookings.filter(b=>b.status==="Confirmed").length;
  const rows=$("adminRows");
  if(!bookings.length){rows.innerHTML='<tr><td colspan="5">No bookings yet.</td></tr>';return;}
  rows.innerHTML=bookings.map(b=>`<tr><td>${b.pnr}</td><td>${b.name}</td><td>${b.trainName}</td><td>${b.from} → ${b.to}</td><td><span class="status ${b.status==="Cancelled"?"cancelled":""}">${b.status}</span></td></tr>`).join("");
}
renderAdmin();
